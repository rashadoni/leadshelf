import { NextResponse, type NextRequest } from "next/server"
import { requireApiSession, unauthorized } from "@/server/http/api-guard"
import { getObject } from "@/server/storage/s3"

export const runtime = "nodejs"

// Media-proxy: бакет наружу не торчит (docs/12), файлы отдает приложение.
// КРИТИЧНО: ключ обязан начинаться с {products|photos|videos}/{org сессии}/ —
// иначе один тенант читал бы медиа другого по прямой ссылке.

export async function GET(
  req: NextRequest,
  { params }: { params: Promise<{ path: string[] }> },
) {
  const session = await requireApiSession(req)
  if (!session) return unauthorized()

  const { path } = await params
  const key = path.join("/")
  const allowed =
    key.startsWith(`products/${session.org}/`) ||
    key.startsWith(`photos/${session.org}/`) ||
    key.startsWith(`videos/${session.org}/`)
  if (!allowed) {
    return NextResponse.json({ error: "forbidden" }, { status: 403 })
  }

  if (key.startsWith(`products/${session.org}/`) && key.endsWith("/demo-pack.svg")) {
    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="640" height="640" viewBox="0 0 640 640" role="img" aria-label="Demo product package">
  <rect width="640" height="640" fill="#f5f5f4"/>
  <rect x="172" y="82" width="296" height="476" rx="34" fill="#ffffff" stroke="#d4d4d4" stroke-width="8"/>
  <rect x="204" y="124" width="232" height="92" rx="18" fill="#dbeafe"/>
  <rect x="204" y="246" width="232" height="24" rx="12" fill="#d4d4d4"/>
  <rect x="204" y="292" width="176" height="18" rx="9" fill="#e5e7eb"/>
  <rect x="204" y="330" width="214" height="18" rx="9" fill="#e5e7eb"/>
  <circle cx="320" cy="442" r="54" fill="#dcfce7" stroke="#16a34a" stroke-width="8"/>
  <text x="320" y="180" text-anchor="middle" fill="#1d4ed8" font-family="Arial, sans-serif" font-size="34" font-weight="700">SKU</text>
  <text x="320" y="456" text-anchor="middle" fill="#15803d" font-family="Arial, sans-serif" font-size="30" font-weight="700">OTC</text>
</svg>`
    return new NextResponse(svg, {
      headers: {
        "Content-Type": "image/svg+xml; charset=utf-8",
        "Cache-Control": "private, max-age=86400",
      },
    })
  }

  if (key.startsWith(`photos/${session.org}/`) && key.endsWith("/demo-proof-001.svg")) {
    const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="960" viewBox="0 0 1280 960" role="img" aria-label="Demo shelf photo proof">
  <rect width="1280" height="960" fill="#f5f5f4"/>
  <rect x="86" y="94" width="1108" height="712" rx="18" fill="#ffffff" stroke="#d4d4d4" stroke-width="10"/>
  <g fill="#e5e7eb">
    <rect x="130" y="226" width="1020" height="28" rx="8"/>
    <rect x="130" y="390" width="1020" height="28" rx="8"/>
    <rect x="130" y="554" width="1020" height="28" rx="8"/>
    <rect x="130" y="718" width="1020" height="28" rx="8"/>
  </g>
  <g font-family="Arial, sans-serif" font-size="26" font-weight="700" text-anchor="middle">
    <g>
      <rect x="180" y="268" width="92" height="118" rx="10" fill="#dbeafe" stroke="#2563eb"/>
      <text x="226" y="334" fill="#1d4ed8">P</text>
      <rect x="288" y="260" width="96" height="126" rx="10" fill="#dbeafe" stroke="#2563eb"/>
      <text x="336" y="329" fill="#1d4ed8">I</text>
      <rect x="400" y="274" width="78" height="112" rx="10" fill="#dcfce7" stroke="#16a34a"/>
      <text x="439" y="336" fill="#15803d">C</text>
    </g>
    <g>
      <rect x="640" y="430" width="84" height="118" rx="10" fill="#ffedd5" stroke="#f97316"/>
      <text x="682" y="496" fill="#c2410c">V</text>
      <rect x="740" y="420" width="92" height="128" rx="10" fill="#dcfce7" stroke="#16a34a"/>
      <text x="786" y="490" fill="#15803d">N</text>
      <rect x="848" y="416" width="110" height="132" rx="10" fill="#fee2e2" stroke="#ef4444"/>
      <text x="903" y="488" fill="#b91c1c">E</text>
    </g>
  </g>
  <text x="92" y="866" fill="#525252" font-family="Arial, sans-serif" font-size="34" font-weight="700">Аптека №1 - фото-подтверждение выкладки</text>
  <text x="92" y="906" fill="#737373" font-family="Arial, sans-serif" font-size="24">Demo proof image generated by LeadShelf media proxy</text>
</svg>`
    return new NextResponse(svg, {
      headers: {
        "Content-Type": "image/svg+xml; charset=utf-8",
        "Cache-Control": "private, max-age=86400",
      },
    })
  }

  const object = await getObject(key)
  if (!object) return NextResponse.json({ error: "not_found" }, { status: 404 })

  return new NextResponse(object.body, {
    headers: {
      "Content-Type": object.contentType,
      "Cache-Control": "private, max-age=86400",
    },
  })
}
