#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const playerDir = resolve(repoRoot, "video/player")
const registryPath = resolve(repoRoot, "apps/web/src/content/help/video-assets.ts")
const outputPath = resolve(repoRoot, "apps/web/src/content/help/video-availability.generated.ts")
const checkOnly = process.argv.includes("--check")

const registry = readFileSync(registryPath, "utf8")
const knownSlugs = new Set([...registry.matchAll(/slug:\s*"([a-z0-9-]+)"/g)].map((match) => match[1]))
const files = existsSync(playerDir) ? readdirSync(playerDir) : []
const media = files.filter((file) => !file.startsWith(".") && file !== "SHA256SUMS")
const pattern = /^([a-z0-9-]+)\.az\.(VOICE\.mp4|poster\.jpg)$/
const pairs = new Map()

for (const file of media) {
  const match = file.match(pattern)
  if (!match) throw new Error(`Unsupported help-video asset (AZ only): ${file}`)
  const [, slug, kind] = match
  if (!knownSlugs.has(slug)) throw new Error(`Help-video asset has no route registry entry: ${file}`)
  const pair = pairs.get(slug) || new Set()
  pair.add(kind)
  pairs.set(slug, pair)
}

const availability = []
for (const [slug, kinds] of [...pairs].sort(([a], [b]) => a.localeCompare(b))) {
  if (!kinds.has("VOICE.mp4") || !kinds.has("poster.jpg")) {
    throw new Error(`Incomplete help-video pair for ${slug}.az (video and poster are both required)`)
  }
  availability.push(`${slug}.az`)
}

const generated = [
  "// Generated by scripts/sync-help-video-availability.mjs. Do not edit manually.",
  "// Only complete Azerbaijani video+poster pairs are listed here.",
  "export const HELP_VIDEO_AVAILABILITY = [",
  ...availability.map((item) => `  "${item}",`),
  "] as const",
  "",
].join("\n")

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : ""
  if (current !== generated) {
    console.error("Help-video availability manifest is stale. Run: pnpm help-video:sync")
    process.exit(1)
  }
  console.log(`[help-video-sync] PASS (${availability.length} AZ guide(s))`)
} else {
  writeFileSync(outputPath, generated)
  console.log(`[help-video-sync] wrote ${availability.length} AZ guide(s)`)
}
